// Generate the gallery's single source entry (src/lib/stageshow.css) from the
// style tree. The package build does the same for dist/stageshow.css.
import { readdir, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'

const root = 'packages/svelte-stageshow/src/lib/style'
const all = []
async function walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) await walk(path)
    else if (entry.name.endsWith('.css')) all.push(path)
  }
}
await walk(root)
const rel = (path) => relative(root, path).replaceAll('\\', '/')
const core = ['stage.css', 'cursor.css', 'keys.css', 'window.css', 'phone.css', 'row.css', 'avatar.css', 'chip.css']
const rank = (path) => {
  const name = rel(path)
  const i = core.indexOf(name)
  if (i >= 0) return [0, i, name]
  if (name.startsWith('motion/')) return [1, 0, name]
  if (name.startsWith('parts/')) return [2, 0, name]
  if (name.startsWith('controls/')) return [3, 0, name]
  return [4, 0, name]
}
all.sort((a, b) => {
  const ra = rank(a)
  const rb = rank(b)
  return ra[0] - rb[0] || ra[1] - rb[1] || ra[2].localeCompare(rb[2])
})
const out = [
  '/* Generated by scripts/sync-css.mjs. Import once in the gallery. */',
  ...all.map((path) => `@import './style/${rel(path)}';`),
].join('\n')
await writeFile('packages/svelte-stageshow/src/lib/stageshow.css', `${out}\n`)
console.log(`${all.length} stylesheets`)
